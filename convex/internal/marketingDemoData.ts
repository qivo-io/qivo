/** Anchor is the Monday displayed as "this week" during a new recording. */
export function assertMarketingAnchor(anchor: string): void {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(anchor)) {
    throw new Error('Marketing demo anchor must be a real Monday in YYYY-MM-DD format')
  }
  const date = new Date(`${anchor}T00:00:00.000Z`)
  if (
    !Number.isFinite(date.getTime()) ||
    date.toISOString().slice(0, 10) !== anchor ||
    date.getUTCDay() !== 1
  ) {
    throw new Error('Marketing demo anchor must be a real Monday in YYYY-MM-DD format')
  }
}

export function marketingDate(anchor: string, dayOffset: number): string {
  assertMarketingAnchor(anchor)
  if (!Number.isSafeInteger(dayOffset))
    throw new Error('Marketing demo date offsets must be safe integers')
  const date = new Date(`${anchor}T00:00:00.000Z`)
  date.setUTCDate(date.getUTCDate() + dayOffset)
  if (!Number.isFinite(date.getTime()))
    throw new Error('Marketing demo date is outside the supported range')
  return date.toISOString().slice(0, 10)
}

/* The seeded times of day (UTC). A person's last Team sync is at
 * DEMO_SYNC_TIME; a hand-off to review or a backdated last write is at
 * DEMO_EVENT_TIME, after that day's sample comments (14:00 plus a minute per
 * same-day reply) and the seeded completions (15:00). */
export const DEMO_SYNC_TIME = '09:10:00.000Z'
export const DEMO_EVENT_TIME = '16:00:00.000Z'

/** The instant `dayOffset` days from the anchor at `time` (UTC). */
export function marketingInstant(anchor: string, dayOffset: number, time: string): string {
  return `${marketingDate(anchor, dayOffset)}T${time}`
}

export function marketingWeek(anchor: string, weekOffset: number): string {
  if (!Number.isSafeInteger(weekOffset))
    throw new Error('Marketing demo week offsets must be safe integers')
  return marketingDate(anchor, weekOffset * 7)
}

/** Application UUID v8 derived from a SHA-256 namespace/key pair. The anchor
 * and dataset version deliberately do not participate: refreshes retain IDs. */
export async function marketingId(namespace: string, key: string): Promise<string> {
  if (!namespace.trim() || !key.trim())
    throw new Error('Marketing demo identifiers require a namespace and key')
  const hash = new Uint8Array(
    await crypto.subtle.digest(
      'SHA-256',
      new TextEncoder().encode(JSON.stringify(['qivo-marketing-demo', namespace, key])),
    ),
  )
  hash[6] = (hash[6] & 0x0f) | 0x80
  hash[8] = (hash[8] & 0x3f) | 0x80
  const hex = [...hash.slice(0, 16)].map((value) => value.toString(16).padStart(2, '0')).join('')
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`
}
