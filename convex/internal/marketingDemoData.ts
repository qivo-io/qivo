export type DemoPerson = {
  key: string
  name: string
  initials: string
  color: string
  role: 'admin' | 'user'
  kind: 'person' | 'agent'
  // Last Team sync, as a negative day offset from the anchor at
  // DEMO_SYNC_TIME. The public demo's anchor is this week's Monday, so 0 or
  // later could lie in the future. Absent = never synced: the page's default
  // reading.
  syncDay?: number
}

export type DemoTeam = {
  key: string
  name: string
  icon: string
  color: string
  lead: string
  members: string[]
}

export type DemoProject = {
  key: string
  code: string
  name: string
  description: string
  parent?: string
  // Root rows retain a preferred team only to choose the stronger explicit
  // share when the demo is seeded. Database projects are team-less.
  team?: string
  lead: string
  icon?: string
  color?: string
}

export type DemoIssue = {
  key: string
  project: string
  title: string
  description: string
  status: IssueStatus
  priority: IssuePriority
  assignee?: string
  // Same edit-access rule as the assignee, never the assignee, never a parent.
  // Owns the task only while it is In Review (lib/review.ts).
  reviewer?: string
  reporter?: string
  archived?: boolean
  parent?: string
  startWeek?: number
  endWeek?: number
  dueDay?: number
  remaining?: number
  paused?: boolean // the reason belongs in the task's comments
  // Handed to review (issues.review_at), as a negative day offset from the
  // anchor at DEMO_EVENT_TIME: every Review task, and a Done task reviewed to
  // Done. Absent = never handed over.
  reviewDay?: number
  // Last written (updated_at and the import activity), as a negative day
  // offset at DEMO_EVENT_TIME, so Team sync reads the task as untouched or
  // its review as waiting. Absent = the seed instant.
  touchedDay?: number
  labels: string[]
}

const ACCEPTANCE_SECTION = '\n\n**Acceptance criteria**\n\n'

function descriptionMarkdown(summary: string, criteria: string[]): string {
  return `${summary}${ACCEPTANCE_SECTION}${criteria.map((item) => `- ${item}`).join('\n')}`
}

type IssueInput = Omit<DemoIssue, 'project' | 'description' | 'priority' | 'labels'> & {
  summary: string
  accept: string[]
  priority?: IssuePriority
  labels?: string[]
}

function inProject(project: string, rows: IssueInput[]): DemoIssue[] {
  return rows.map(({ summary, accept, priority = 'medium', labels = [], ...row }) => ({
    ...row,
    project,
    priority,
    labels,
    description: descriptionMarkdown(summary, accept),
  }))
}

