function Icon({
  name,
  size = 16,
  color = 'currentColor',
  strokeWidth = 1.75,
  style,
  className,
}: {
  name: string
  size?: number
  color?: string
  strokeWidth?: number
  style?: CSSProperties
  className?: string
}) {
  const Glyph = LUCIDE_ICONS[name] ?? CircleHelp
  return (
    <Glyph
      size={size}
      color={color}
      strokeWidth={strokeWidth}
      style={{ width: size, height: size, color, ...style }}
      className={cn('[flex-shrink:0] [display:block]', className)}
      aria-hidden="true"
    />
  )
}

